/**
 * Emit the product package's committed brand-derived modules from
 * brand/brand.config.json — the same single operator-editable source the
 * shell uses, narrowed to the surface the product layer consumes:
 *
 * - `src/generated-product-identity.ts`  BRAND_VARIANT / BRAND_TENANT /
 *   BRAND_TENANT_ID / BRAND_DISPLAY_NAME
 * - `src/generated-brand-assets.ts`      heroBrandDataUrl (client bundle)
 *
 * The browser half is a static bundle, so runtime injection cannot reach it;
 * the identity therefore ships as generated constants verified against the
 * shared config by `verify-brand-sync.mjs`.
 */

import { readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { loadBrandConfig } from '../../scripts/brand-config.mjs'

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const repositoryRoot = resolve(packageRoot, '..')

const defaultOutputs = {
  identityModule: resolve(packageRoot, 'src/generated-product-identity.ts'),
  brandAssets: resolve(packageRoot, 'src/generated-brand-assets.ts'),
}

/** Render the committed identity module in memory. */
export function renderProductIdentityModule(environment = process.env) {
  const config = loadBrandConfig(environment, repositoryRoot)
  return `/** Generated by scripts/generate-brand-module.mjs from brand/brand.config.json. Do not edit directly. */

/** Build-time white-label variant, widened so either brand's sources typecheck. */
export type BrandVariant = 'sensteed'

/** Build-time white-label variant. */
export const BRAND_VARIANT: BrandVariant = ${JSON.stringify(config.variant ?? 'sensteed')}

/** Tenant identity bound to the build-time brand. */
export const BRAND_TENANT = ${JSON.stringify(config.tenant)} as const

/** Stable tenant id accepted by the activation gate for this brand only. */
export const BRAND_TENANT_ID = ${JSON.stringify(config.tenantId)} as const

/** Display names shown in chrome that is identical across release channels. */
export const BRAND_DISPLAY_NAME = Object.freeze({
  titlebar: ${JSON.stringify(config.displayName.titlebar)},
  locale: ${JSON.stringify(config.displayName.locale)},
})
`
}

/** Render the committed client brand assets module in memory. */
export async function renderProductBrandAssets(environment = process.env) {
  const config = loadBrandConfig(environment, repositoryRoot)
  const heroPath = resolve(repositoryRoot, config.artwork.heroMark)
  const hero = sharp(heroPath)
  const metadata = await hero.metadata()
  if (metadata.format !== 'png' || !metadata.hasAlpha) {
    throw new Error(`generate-brand-module: ${heroPath} must be an RGBA PNG`)
  }
  const data = await readFile(heroPath)
  return `/** Generated by scripts/generate-brand-module.mjs. Do not edit directly. */

export const heroBrandDataUrl = ${JSON.stringify(`data:image/png;base64,${data.toString('base64')}`)}
`
}

/**
 * Write both committed outputs, returning their paths.
 * @param {object} [options]
 * @param {NodeJS.ProcessEnv | undefined} [options.environment]
 * @param {{ identityModule?: string, brandAssets?: string }} [options.outputs]
 *   redirect the emitted files (white-label round-trip tests).
 */
export async function writeProductBrandModules({ environment, outputs } = {}) {
  const targets = { ...defaultOutputs, ...outputs }
  await writeFile(targets.identityModule, renderProductIdentityModule(environment))
  await writeFile(targets.brandAssets, await renderProductBrandAssets(environment))
  return targets
}

const invokedPath = process.argv[1]
if (invokedPath !== undefined && resolve(invokedPath) === fileURLToPath(import.meta.url)) {
  const outputs = {
    ...(process.env.BRAND_OUTPUT_IDENTITY !== undefined
      ? { identityModule: resolve(process.env.BRAND_OUTPUT_IDENTITY) }
      : {}),
    ...(process.env.BRAND_OUTPUT_ASSETS !== undefined
      ? { brandAssets: resolve(process.env.BRAND_OUTPUT_ASSETS) }
      : {}),
  }
  const written = await writeProductBrandModules({ environment: process.env, outputs })
  console.log('product brand modules written:')
  for (const path of Object.values(written)) console.log(`  ${path}`)
}
