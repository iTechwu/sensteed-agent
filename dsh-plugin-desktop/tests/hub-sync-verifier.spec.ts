import { generateKeyPairSync, randomUUID, sign } from 'node:crypto'
import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import { hubCanonicalJson, hubSyncDigest, hubSyncSnapshotData, verifyHubSyncSnapshot, type HubReleaseTrust, type HubSyncExpected } from '../src/hub-sync-verifier.ts'

function fixture() {
  const now = Date.now(), pair = generateKeyPairSync('ed25519')
  const trust: HubReleaseTrust = { schemaVersion: 1, keys: { test: pair.publicKey.export({ type: 'spki', format: 'der' }).toString('base64') }, revokedKeyIds: [] }
  const expected: HubSyncExpected = { origin: 'https://ai.hozonauto.com/plugins/api', tenantId: randomUUID(), actorRef: 'sso:user@example.com',
    deviceId: randomUUID(), profileId: randomUUID(), channel: 'stable', observedStateDigest: 'a'.repeat(64), minimumPolicyRevision: 1,
    target: { sensteedVersion: '0.2.1-alpha.3-beta.202610180853', harnessVersion: '0.2.1-alpha.3', os: 'darwin', arch: 'arm64', nodeVersion: '22.0.0',
      cordisVersion: '4.0.5-alpha.2', libc: null, nodeAbi: '127', hostCapabilities: ['credentials'] } }
  const { minimumPolicyRevision: _minimum, ...binding } = expected
  const snapshot = { ...binding, schemaVersion: 'hub-sync-v1', snapshotId: randomUUID(), policyRevision: 2, catalogDigest: 'b'.repeat(64),
    entries: [{ kind: 'skill', itemId: randomUUID(), displayName: 'Example', identity: 'example', initialInstall: true, required: false,
      offlineBootstrap: false, enabled: true, releaseId: randomUUID(), version: '1.0.0', artifactDigest: 'c'.repeat(64), channelRevision: 2,
      bytes: 42, disposition: 'INSTALL', reason: null }], issuedAt: new Date(now).toISOString(), expiresAt: new Date(now + 300_000).toISOString() }
  function signed(value = snapshot) { return { snapshot: value, signature: { algorithm: 'Ed25519', canonicalization: 'RFC8785', keyId: 'test',
    payloadDigest: hubSyncDigest(value), signature: sign(null, Buffer.from(hubCanonicalJson(value)), pair.privateKey).toString('base64') } } }
  return { now, trust, expected, snapshot, signed }
}
describe('desktop L0 Hub catalog signature boundary', () => {
  it('accepts the committed signature generated by the Hub canonical implementation', () => {
    const f = JSON.parse(readFileSync(new URL('./fixtures/hub-sync-v1/valid.json', import.meta.url), 'utf8'))
    expect(hubSyncSnapshotData(verifyHubSyncSnapshot(f.value, f.trust, f.expected, f.at)).snapshotId).toBe(f.value.snapshot.snapshotId)
  })
  it('verifies a Hub-shaped snapshot with real Ed25519 and freezes cloned observable data', () => {
    const f = fixture(), value = f.signed(), capability = verifyHubSyncSnapshot(value, f.trust, f.expected, f.now)
    const data = hubSyncSnapshotData(capability)
    f.snapshot.entries[0]!.displayName = 'tampered'
    expect(data.entries[0]!.displayName).toBe('Example')
    expect(Object.isFrozen(data.target.hostCapabilities)).toBe(true)
    expect(() => hubSyncSnapshotData({} as never)).toThrow('invalid snapshot capability')
  })
  it.each(['tenantId', 'deviceId', 'profileId', 'actorRef', 'origin', 'observedStateDigest'] as const)('rejects a valid signature for another %s', field => {
    const f = fixture()
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, { ...f.expected, [field]: 'other' }, f.now)).toThrow('binding mismatch')
  })
  it('rejects modified bytes, revoked keys and a different exact Host target', () => {
    const f = fixture(), value = f.signed()
    value.snapshot.entries[0]!.displayName = 'modified'
    expect(() => verifyHubSyncSnapshot(value, f.trust, f.expected, f.now)).toThrow('digest mismatch')
    expect(() => verifyHubSyncSnapshot(f.signed(), { ...f.trust, revokedKeyIds: ['test'] }, f.expected, f.now)).toThrow('untrusted signing key')
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, { ...f.expected, target: { ...f.expected.target, nodeAbi: '128' } }, f.now)).toThrow('target binding mismatch')
  })
  it('rejects invalid signature bytes even when the attacker recomputes the digest', () => {
    const f = fixture(), value = f.signed()
    value.snapshot.entries[0]!.displayName = 'modified'
    value.signature.payloadDigest = hubSyncDigest(value.snapshot)
    expect(() => verifyHubSyncSnapshot(value, f.trust, f.expected, f.now)).toThrow('invalid signature')
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, { ...f.expected, channel: 'beta' }, f.now)).toThrow('channel binding mismatch')
    expect(() => verifyHubSyncSnapshot({ ...f.signed(), surprise: true }, f.trust, f.expected, f.now)).toThrow()
    expect(() => verifyHubSyncSnapshot(f.signed({ ...f.snapshot, target: { ...f.snapshot.target, surprise: true } as typeof f.snapshot.target }), f.trust, f.expected, f.now)).toThrow()
  })
  it('rejects expired, future, overlong and policy rollback snapshots even when signed', () => {
    const f = fixture()
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, f.expected, f.now + 300_001)).toThrow('lifetime')
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, f.expected, f.now - 31_000)).toThrow('lifetime')
    expect(() => verifyHubSyncSnapshot(f.signed({ ...f.snapshot, expiresAt: new Date(f.now + 301_000).toISOString() }), f.trust, f.expected, f.now)).toThrow('lifetime')
    expect(() => verifyHubSyncSnapshot(f.signed(), f.trust, { ...f.expected, minimumPolicyRevision: 3 }, f.now)).toThrow('rollback')
  })
  it('rejects duplicate identities and incomplete ready release evidence', () => {
    const f = fixture()
    expect(() => verifyHubSyncSnapshot(f.signed({ ...f.snapshot, entries: [...f.snapshot.entries, ...f.snapshot.entries] }), f.trust, f.expected, f.now)).toThrow('duplicate')
    const invalid = { ...f.snapshot, entries: [{ ...f.snapshot.entries[0]!, bytes: 0 }] }
    expect(() => verifyHubSyncSnapshot(f.signed(invalid), f.trust, f.expected, f.now)).toThrow('incomplete')
  })
  it('rejects non-JSON Unicode and objects outside the Hub I-JSON contract', () => {
    expect(() => hubCanonicalJson('\ud800')).toThrow('Unicode')
    expect(() => hubCanonicalJson({ value: undefined })).toThrow('non-JSON')
    expect(() => hubCanonicalJson(new Date())).toThrow('non-JSON')
    expect(() => hubCanonicalJson(new Array(2))).toThrow('sparse array')
    expect(hubCanonicalJson({ '\ufffd': 1, '\u20ac': 2, '\r': 3, a: 1e30, b: 0.000000000000000000000000001, z: -0 })).toBe('{"\\r":3,"a":1e+30,"b":1e-27,"z":0,"€":2,"�":1}')
  })
})
